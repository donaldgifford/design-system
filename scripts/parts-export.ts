/**
 * The part stylesheets: one small CSS file per component, block and shell
 * part, holding an `@source` line for that part's file and for every
 * package file it imports, however far down. An app on `core.css` imports
 * one per part it uses and cannot miss a part's dependency:
 *
 *   @import "@donaldgifford/design-system/parts/shell/sidebar-tree.css";
 *
 * `just parts` writes them under src/styles/parts, and a test fails when
 * they and the imports disagree, so they are never edited by hand.
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";

const src = join(import.meta.dir, "../src");
export const partsDir = join(src, "styles/parts");

/** Where each kind of module lives under src, and its extension. */
const kinds = {
  components: { dir: "components/ui", ext: ".tsx" },
  blocks: { dir: "components/blocks", ext: ".tsx" },
  shell: { dir: "components/shell", ext: ".tsx" },
  lib: { dir: "lib", ext: ".ts" },
  hooks: { dir: "hooks", ext: ".ts" },
} as const;

type Kind = keyof typeof kinds;

/** The kinds that get a stylesheet: the ones an app renders. */
const partKinds = ["components", "blocks", "shell"] as const satisfies readonly Kind[];

const isKind = (value: string): value is Kind => value in kinds;

/** A module's file, relative to src: `components/button` is `components/ui/button.tsx`. */
function fileOf(kind: Kind, name: string): string {
  return `${kinds[kind].dir}/${name}${kinds[kind].ext}`;
}

/** The package modules a file imports, as files relative to src. */
function importsOf(file: string): string[] {
  const code = readFileSync(join(src, file), "utf8");
  const found: string[] = [];
  for (const match of code.matchAll(/["']@donaldgifford\/design-system\/([\w-]+)\/([\w-]+)["']/g)) {
    const [, kind, name] = match;
    if (kind && name && isKind(kind)) found.push(fileOf(kind, name));
  }
  return found;
}

/** A file and everything it imports from the package, however far down, sorted. */
export function closure(file: string): string[] {
  const seen = new Set<string>();
  const queue = [file];
  for (let next = queue.pop(); next !== undefined; next = queue.pop()) {
    if (seen.has(next)) continue;
    seen.add(next);
    queue.push(...importsOf(next));
  }
  seen.delete(file);
  return [file, ...[...seen].sort()];
}

/** Every part: `components/button`, `shell/sidebar-tree`, and so on. */
export function parts(): { part: string; file: string }[] {
  return partKinds.flatMap((kind) =>
    readdirSync(join(src, kinds[kind].dir))
      .filter((name) => name.endsWith(kinds[kind].ext) && !name.includes(".stories."))
      .sort()
      .map((name) => {
        const module = name.slice(0, -kinds[kind].ext.length);
        return { part: `${kind}/${module}`, file: fileOf(kind, module) };
      }),
  );
}

/** One part's stylesheet. */
export function render(part: string, file: string): string {
  const from = dirname(join(partsDir, `${part}.css`));
  const lines = closure(file).map((path) => `@source "${relative(from, join(src, path))}";`);
  return [
    `/* Generated by \`just parts\` from the imports of src/${file}; do not edit by hand. */`,
    ...lines,
    "",
  ].join("\n");
}

/** Every stylesheet, by its path under src/styles/parts. */
export function exportParts(): Map<string, string> {
  return new Map(parts().map(({ part, file }) => [`${part}.css`, render(part, file)]));
}

if (import.meta.main) {
  rmSync(partsDir, { recursive: true, force: true });
  for (const [path, css] of exportParts()) {
    mkdirSync(dirname(join(partsDir, path)), { recursive: true });
    writeFileSync(join(partsDir, path), css);
  }
}
